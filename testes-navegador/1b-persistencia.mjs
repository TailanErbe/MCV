import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL ?? 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1366, height: 900 } });
const page = await ctx.newPage();
await page.goto(process.env.DEMO_URL ?? 'http://localhost:4173/');
await page.waitForSelector('.balance');
const s1 = await page.evaluate(() => JSON.parse(localStorage.getItem('igreja-mcv-demonstracao') ?? 'null'));
console.log(s1?.version === 2 && s1.data.transactions.length === 60 ? 'OK   dados gravados ao abrir (versão 2, 60 movimentos: sede e congregações)' : 'FALHA gravação inicial');
await page.click('button:has-text("Restaurar demonstração")');
await page.click('dialog[open] button:has-text("Restaurar")');
await new Promise((r) => setTimeout(r, 350));
const s2 = await page.evaluate(() => localStorage.getItem('igreja-mcv-demonstracao'));
console.log(s2 === null ? 'OK   restaurar apaga as alterações salvas' : 'FALHA restaurar não limpou');
await page.reload();
await page.waitForSelector('.balance');
const txt = (await page.locator('.balances').innerText()).replace(/\s/g, ' ');
console.log(txt.includes('R$ 22.293,83') ? 'OK   após recarregar, base original com total R$ 22.293,83' : 'FALHA base após recarregar');
const s3 = await page.evaluate(() => JSON.parse(localStorage.getItem('igreja-mcv-demonstracao') ?? 'null'));
console.log(s3?.version === 2 ? 'OK   base gravada de novo após recarregar' : 'FALHA regravação');
await browser.close();
